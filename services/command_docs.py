"""Справочник команд бота для веб-страницы документации (/commands) — статичные
данные, а не автосборка из disnake-команд, потому что нужен человеческий,
плейн-русский текст "зачем это", а не голая сигнатура/description= (см. память
feedback_discord_guide_formatting — тот же урок для веб-версии). Источник
правды по уровням доступа — main.py (ALWAYS_ALLOWED_COMMANDS,
MEMBER_ACCESSIBLE_COMMANDS, дефолт "officer") и точечные @commands.check на
конкретных сабкомандах (антиспам-настройки, /гильдия, /админы — везде
super_admin) — при добавлении новой команды сверяться с main.py, а не
угадывать уровень.

ACCESS_LABELS — (подпись, css-класс бейджа) на каждый уровень; используется
и в docs.html построчно, и в шапке легенды."""

ACCESS_LABELS = {
    "any": ("Открыто всем", "badge-ok"),
    "member": ("Участник гильдии", "badge-neutral"),
    # Участнику — только про себя (свой аккаунт/альт), чужие и вся гильдия — офицеру.
    "self": ("Участник — про себя", "badge-neutral"),
    "officer": ("Офицер / лидер", "badge-warn"),
    "super_admin": ("Супер-админ", "badge-danger"),
}


def public_command_docs():
    """/commands — публичная страница без авторизации, поэтому супер-админские
    команды (владелец бота: /гильдия, /админы, антиспам-настройки в /настройки)
    из неё нужно полностью убрать, а не просто визуально спрятать — само их
    существование/сигнатура не для посторонних глаз. Возвращает (sections,
    access_labels) — секции без единой публичной команды выбрасываются целиком,
    а не остаются пустым заголовком; access_labels — без бейджа "Супер-админ"
    (иначе легенда наверху всё равно намекала бы на скрытый уровень)."""
    sections = []
    for section in COMMAND_DOCS:
        commands = [c for c in section["commands"] if c["access"] != "super_admin"]
        if commands:
            sections.append({**section, "commands": commands})
    labels = {k: v for k, v in ACCESS_LABELS.items() if k != "super_admin"}
    return sections, labels

